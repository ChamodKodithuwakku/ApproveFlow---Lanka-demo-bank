// "Generate AI Risk Summary" on the application details page.
// The response is rendered with textContent only, so model output can never inject markup (XSS-safe).
(function () {
    "use strict";

    var card = document.getElementById("riskSummaryCard");
    var button = document.getElementById("riskSummaryButton");
    if (!card || !button) {
        return;
    }

    var tokenInput = card.querySelector("input[name='__RequestVerificationToken']");
    var spinner = document.getElementById("riskSummarySpinner");
    var icon = document.getElementById("riskSummaryIcon");
    var errorBox = document.getElementById("riskSummaryError");
    var result = document.getElementById("riskSummaryResult");
    var placeholder = document.getElementById("riskSummaryPlaceholder");

    function busy(on) {
        button.disabled = on;
        spinner.classList.toggle("d-none", !on);
        icon.classList.toggle("d-none", on);
    }

    function showError(message) {
        errorBox.textContent = message;
        errorBox.classList.remove("d-none");
    }

    button.addEventListener("click", function () {
        busy(true);
        errorBox.classList.add("d-none");

        fetch(card.dataset.url, {
            method: "POST",
            credentials: "same-origin",
            headers: { "X-CSRF-TOKEN": tokenInput ? tokenInput.value : "", "Accept": "application/json" }
        })
            .then(function (response) {
                if (!response.ok) {
                    throw new Error(response.status === 429
                        ? "Too many requests. Please wait a moment and try again."
                        : "The risk summary could not be generated (HTTP " + response.status + ").");
                }
                return response.json();
            })
            .then(function (data) {
                var level = document.getElementById("riskSummaryLevel");
                level.textContent = data.riskLevel + " risk";
                level.className = "af-risk af-risk-" + String(data.riskLevel).toLowerCase();

                document.getElementById("riskSummarySource").textContent =
                    (data.isFallback ? "Rule-based assessment" : "Generated by " + data.model) + " · " + data.generatedAt;
                document.getElementById("riskSummaryText").textContent = data.summary;

                var list = document.getElementById("riskSummaryFactors");
                list.replaceChildren();
                (data.factors || []).forEach(function (factor) {
                    var li = document.createElement("li");
                    li.textContent = factor;
                    list.appendChild(li);
                });

                placeholder.classList.add("d-none");
                result.classList.remove("d-none");
            })
            .catch(function (error) {
                showError(error.message);
            })
            .finally(function () {
                busy(false);
            });
    });
})();
