using System.Runtime.CompilerServices;
using System.Text.Json;
using System.Text.Json.Serialization;
using ApproveFlow.Application.Common.Interfaces;
using ApproveFlow.Domain.Common;
using ApproveFlow.Domain.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Storage;

namespace ApproveFlow.Infrastructure.Persistence.Interceptors;

/// <summary>
/// Writes an <see cref="AuditLog"/> row for every insert, update and delete of an audited entity, in the same
/// database transaction as the change itself — either both are committed or neither is.
/// </summary>
/// <remarks>
/// Rows whose primary key is generated by the database (identity columns) do not know their key until after the
/// INSERT. For those the interceptor opens a transaction (unless the caller already has one), lets EF insert the
/// data, then writes the audit rows with the real keys and commits.
/// </remarks>
public sealed class AuditTrailInterceptor : SaveChangesInterceptor
{
    /// <summary>Columns never written to the audit trail: secrets, concurrency tokens and login-counter noise.</summary>
    private static readonly HashSet<string> ExcludedProperties = new(StringComparer.Ordinal)
    {
        "RowVersion", "PasswordHash", "SecurityStamp", "ConcurrencyStamp", "NormalizedEmail", "NormalizedUserName",
        "AccessFailedCount", "LockoutEnd",
    };

    /// <summary>Stamp columns are redundant in update diffs: the audit row records who and when itself.</summary>
    private static readonly HashSet<string> StampProperties = new(StringComparer.Ordinal)
    {
        nameof(AuditableEntity.UpdatedAtUtc), nameof(AuditableEntity.UpdatedById), nameof(AuditableEntity.UpdatedByName),
    };

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        Converters = { new JsonStringEnumConverter() },
        DefaultIgnoreCondition = JsonIgnoreCondition.Never,
    };

    private readonly ICurrentUser _currentUser;
    private readonly TimeProvider _clock;
    private readonly ConditionalWeakTable<DbContext, PendingAudit> _pending = new();

    public AuditTrailInterceptor(ICurrentUser currentUser, TimeProvider clock)
    {
        _currentUser = currentUser;
        _clock = clock;
    }

    public override InterceptionResult<int> SavingChanges(DbContextEventData eventData, InterceptionResult<int> result)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context)
        {
            var pending = Capture(context);
            if (pending.Deferred.Count > 0)
            {
                if (context.Database.CurrentTransaction is null && context.Database.IsRelational())
                {
                    pending.OwnedTransaction = context.Database.BeginTransaction();
                }

                _pending.AddOrUpdate(context, pending);
            }
        }

        return base.SavingChanges(eventData, result);
    }

    public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(DbContextEventData eventData, InterceptionResult<int> result,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context)
        {
            var pending = Capture(context);
            if (pending.Deferred.Count > 0)
            {
                if (context.Database.CurrentTransaction is null && context.Database.IsRelational())
                {
                    pending.OwnedTransaction = await context.Database.BeginTransactionAsync(cancellationToken);
                }

                _pending.AddOrUpdate(context, pending);
            }
        }

        return await base.SavingChangesAsync(eventData, result, cancellationToken);
    }

    public override int SavedChanges(SaveChangesCompletedEventData eventData, int result)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context && _pending.TryGetValue(context, out var pending))
        {
            _pending.Remove(context);
            try
            {
                context.Set<AuditLog>().AddRange(pending.Deferred.Select(d => d.ToAuditLog(pending.AuditContext)));
                context.SaveChanges();
                pending.OwnedTransaction?.Commit();
            }
            catch
            {
                pending.OwnedTransaction?.Rollback();
                throw;
            }
            finally
            {
                pending.OwnedTransaction?.Dispose();
            }
        }

        return base.SavedChanges(eventData, result);
    }

    public override async ValueTask<int> SavedChangesAsync(SaveChangesCompletedEventData eventData, int result,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context && _pending.TryGetValue(context, out var pending))
        {
            _pending.Remove(context);
            try
            {
                context.Set<AuditLog>().AddRange(pending.Deferred.Select(d => d.ToAuditLog(pending.AuditContext)));
                await context.SaveChangesAsync(cancellationToken);
                if (pending.OwnedTransaction is not null)
                {
                    await pending.OwnedTransaction.CommitAsync(cancellationToken);
                }
            }
            catch
            {
                if (pending.OwnedTransaction is not null)
                {
                    await pending.OwnedTransaction.RollbackAsync(CancellationToken.None);
                }

                throw;
            }
            finally
            {
                if (pending.OwnedTransaction is not null)
                {
                    await pending.OwnedTransaction.DisposeAsync();
                }
            }
        }

        return await base.SavedChangesAsync(eventData, result, cancellationToken);
    }

    public override void SaveChangesFailed(DbContextErrorEventData eventData)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context && _pending.TryGetValue(context, out var pending))
        {
            _pending.Remove(context);
            pending.OwnedTransaction?.Rollback();
            pending.OwnedTransaction?.Dispose();
        }

        base.SaveChangesFailed(eventData);
    }

    public override async Task SaveChangesFailedAsync(DbContextErrorEventData eventData, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        if (eventData.Context is { } context && _pending.TryGetValue(context, out var pending))
        {
            _pending.Remove(context);
            if (pending.OwnedTransaction is not null)
            {
                await pending.OwnedTransaction.RollbackAsync(CancellationToken.None);
                await pending.OwnedTransaction.DisposeAsync();
            }
        }

        await base.SaveChangesFailedAsync(eventData, cancellationToken);
    }

    /// <summary>
    /// Builds audit rows for the current change set. Rows with known keys are added to the context immediately
    /// (same INSERT batch); rows that depend on database-generated keys are returned as deferred.
    /// </summary>
    private PendingAudit Capture(DbContext context)
    {
        // The audit log itself is append-only: refuse any attempt to change or remove existing rows.
        foreach (var entry in context.ChangeTracker.Entries<AuditLog>())
        {
            if (entry.State is EntityState.Modified or EntityState.Deleted)
            {
                throw new InvalidOperationException("Audit log records are append-only and cannot be modified or deleted.");
            }
        }

        var auditContext = new AuditContext(
            _currentUser.IsAuthenticated ? _currentUser.UserId : AuditableEntityInterceptor.SystemUserId,
            _currentUser.IsAuthenticated ? _currentUser.UserName : AuditableEntityInterceptor.SystemUserName,
            _currentUser.IpAddress,
            _currentUser.CorrelationId,
            _clock.GetUtcNow().UtcDateTime);

        var pending = new PendingAudit(auditContext);
        var immediate = new List<AuditLog>();

        foreach (var entry in context.ChangeTracker.Entries().ToList())
        {
            if (entry.Entity is AuditLog || entry.State is EntityState.Detached or EntityState.Unchanged || !AuditScope.IsAudited(entry.Entity))
            {
                continue;
            }

            var auditEntry = AuditEntry.TryCreate(entry);
            if (auditEntry is null)
            {
                continue;
            }

            if (auditEntry.HasTemporaryKey)
            {
                pending.Deferred.Add(auditEntry);
            }
            else
            {
                immediate.Add(auditEntry.ToAuditLog(auditContext));
            }
        }

        context.Set<AuditLog>().AddRange(immediate);
        return pending;
    }

    private sealed class PendingAudit
    {
        public PendingAudit(AuditContext auditContext)
        {
            AuditContext = auditContext;
        }

        public AuditContext AuditContext { get; }
        public List<AuditEntry> Deferred { get; } = new();
        public IDbContextTransaction? OwnedTransaction { get; set; }
    }

    private sealed class AuditEntry
    {
        private readonly EntityEntry _entry;
        private readonly string _action;
        private readonly Dictionary<string, object?> _oldValues = new(StringComparer.Ordinal);
        private readonly Dictionary<string, object?> _newValues = new(StringComparer.Ordinal);
        private readonly List<string> _changedColumns = new();

        private AuditEntry(EntityEntry entry, string action)
        {
            _entry = entry;
            _action = action;
            TableName = entry.Metadata.GetTableName() ?? entry.Metadata.ClrType.Name;
        }

        public string TableName { get; }

        public bool HasTemporaryKey => _entry.Properties.Any(p => p.Metadata.IsPrimaryKey() && p.IsTemporary);

        public static AuditEntry? TryCreate(EntityEntry entry)
        {
            var action = entry.State switch
            {
                EntityState.Added => "Insert",
                EntityState.Deleted => "Delete",
                EntityState.Modified when IsSoftDelete(entry) => "SoftDelete",
                EntityState.Modified => "Update",
                _ => null,
            };

            if (action is null)
            {
                return null;
            }

            var audit = new AuditEntry(entry, action);
            foreach (var property in entry.Properties)
            {
                var name = property.Metadata.Name;
                if (ExcludedProperties.Contains(name) || property.Metadata.IsPrimaryKey())
                {
                    continue;
                }

                switch (entry.State)
                {
                    case EntityState.Added:
                        // Values for added rows are read after the insert (see ToAuditLog) so generated values are included.
                        break;
                    case EntityState.Deleted:
                        audit._oldValues[name] = property.OriginalValue;
                        break;
                    case EntityState.Modified when property.IsModified && !Equals(property.OriginalValue, property.CurrentValue)
                                                   && !StampProperties.Contains(name):
                        audit._oldValues[name] = property.OriginalValue;
                        audit._newValues[name] = property.CurrentValue;
                        audit._changedColumns.Add(name);
                        break;
                }
            }

            // An update that only touched excluded/stamp columns (e.g. a failed-login counter) is not business-relevant.
            return entry.State == EntityState.Modified && audit._changedColumns.Count == 0 ? null : audit;
        }

        public AuditLog ToAuditLog(AuditContext context)
        {
            if (_action == "Insert")
            {
                foreach (var property in _entry.Properties)
                {
                    if (!ExcludedProperties.Contains(property.Metadata.Name) && !property.Metadata.IsPrimaryKey())
                    {
                        _newValues[property.Metadata.Name] = property.CurrentValue;
                    }
                }
            }

            var key = string.Join(",", _entry.Properties
                .Where(p => p.Metadata.IsPrimaryKey())
                .Select(p => Convert.ToString(p.CurrentValue, System.Globalization.CultureInfo.InvariantCulture)));

            return AuditLog.ForEntityChange(
                TableName,
                key,
                _action,
                _oldValues.Count == 0 ? null : JsonSerializer.Serialize(_oldValues, JsonOptions),
                _newValues.Count == 0 ? null : JsonSerializer.Serialize(_newValues, JsonOptions),
                _changedColumns.Count == 0 ? null : string.Join(",", _changedColumns),
                context);
        }

        private static bool IsSoftDelete(EntityEntry entry) =>
            entry.Entity is ISoftDeletable
            && entry.Properties.FirstOrDefault(p => p.Metadata.Name == nameof(ISoftDeletable.IsDeleted)) is { } flag
            && flag.OriginalValue is false
            && flag.CurrentValue is true;
    }
}
